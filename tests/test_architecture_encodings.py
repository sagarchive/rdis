"""Independent, byte-exact decoder smoke fixtures for every advertised machine ISA.

Encodings are fixed byte sequences, not bytes generated by RDIS. Assertions focus on instruction
boundaries and lengths; they deliberately do not claim broad opcode or function-discovery coverage.
RISC-V encoding lengths and canonical NOP/C.NOP rules are documented at:
https://docs.riscv.org/reference/isa/unpriv/rv32.html
https://docs.riscv.org/reference/isa/unpriv/c-st-ext.html
ARM NOP behavior is documented at:
https://documentation-service.arm.com/static/6245c734b059dc5ff9a8bdab
"""
import unittest

from rdis.arch import make


class ArchitectureEncodingFixtureTests(unittest.TestCase):
    BASE = 0x1000

    def assert_decode_sizes(self, name, code, expected_sizes, *, thumb=False):
        decoder = make(name)
        decoded = list(decoder.decode_run(code, self.BASE, thumb=thumb))
        actual = [(insn.address, insn.size) for insn in decoded]
        expected = []
        address = self.BASE
        for size in expected_sizes:
            expected.append((address, size))
            address += size
        self.assertEqual(actual, expected, f"{name} / thumb={thumb}: {decoded!r}")
        self.assertTrue(all(insn.mnemonic and insn.op_str is not None for insn in decoded))

    def test_x86_and_x86_64_instruction_boundaries(self):
        code = bytes.fromhex("90 c3")  # NOP; RET
        for name in ("x86", "x86_64"):
            with self.subTest(arch=name):
                self.assert_decode_sizes(name, code, [1, 1])

    def test_arm64_instruction_boundaries(self):
        code = bytes.fromhex("1f 20 03 d5 c0 03 5f d6")  # A64 NOP; RET
        self.assert_decode_sizes("arm64", code, [4, 4])

    def test_arm_and_thumb_modes_use_their_own_instruction_widths(self):
        arm_code = bytes.fromhex("00 f0 20 e3 1e ff 2f e1")  # A32 NOP; BX LR
        thumb_code = bytes.fromhex("00 bf 70 47")             # T16 NOP; BX LR
        self.assert_decode_sizes("arm", arm_code, [4, 4])
        self.assert_decode_sizes("arm", thumb_code, [2, 2], thumb=True)

    def test_mips32_and_mips64_both_endiannesses(self):
        # MIPS NOP followed by JR $ra. Endian-specific byte order is deliberate.
        samples = {
            "mips": bytes.fromhex("00 00 00 00 03 e0 00 08"),
            "mipsel": bytes.fromhex("00 00 00 00 08 00 e0 03"),
            "mips64": bytes.fromhex("00 00 00 00 03 e0 00 08"),
            "mips64el": bytes.fromhex("00 00 00 00 08 00 e0 03"),
        }
        for name, code in samples.items():
            with self.subTest(arch=name):
                self.assert_decode_sizes(name, code, [4, 4])

    def test_riscv32_and_riscv64_base_instruction_boundaries(self):
        code = bytes.fromhex("13 00 00 00 67 80 00 00")  # ADDI x0,x0,0; JALR x0,0(ra)
        for name in ("riscv32", "riscv64"):
            with self.subTest(arch=name):
                self.assert_decode_sizes(name, code, [4, 4])

    def test_riscv_compressed_instruction_boundaries(self):
        code = bytes.fromhex("01 00 82 80")  # C.NOP; C.JR ra (RET alias)
        for name in ("riscv32", "riscv64"):
            with self.subTest(arch=name):
                self.assert_decode_sizes(name, code, [2, 2])


if __name__ == "__main__":
    unittest.main()
